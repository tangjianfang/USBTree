def ts(t):
    return f"{int(t // 60)}:{int(t % 60):02d}"


def main():
    # videos.yaml 结构简单（每条一层键值），用正则读，免装 PyYAML
    meta = {}
    for blk in re.split(r"\n  - ", (HERE / "videos.yaml").read_text(encoding="utf-8"))[1:]:
        kv = dict(re.findall(r"^\s*(\w+):\s*(.+)$", "id: " + blk.split(":", 1)[1], re.M))
        meta[kv["id"].strip()] = {k: v.strip() for k, v in kv.items()}
    DST.mkdir(exist_ok=True)
    for f in sorted(OUT.glob("*.cues.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        vid = d["slug"]
        m = meta.get(vid)
        if not m:
            continue
        lines = [f"# {m['title']} · 旁白与字幕稿", "",
                 f"> 视频 `{vid}` · 时长约 {ts(d['duration'])} · 场景源码 [../scenes/{m['scene']}](../scenes/{m['scene']}) · 成品 `site/public/videos/{vid}.mp4`",
                 "> 字幕由场景运行时自动记录（`USBScene.say()`），改字幕请改场景源码后重新渲染，再运行 `python3 videos/tools/gen_scripts.py`。", "",
                 "## 内容简介", "", m["summary"], "", "## 旁白 / 字幕", "", "| 时间 | 字幕 |", "|---|---|"]
        for c in d["cues"]:
            lines.append(f"| {ts(c['start'])} | {c['text'].replace('|', '／')} |")
        lines += ["", "## 规范核对表", "", "画面里出现的每个数字、编码和时序都对到了规范原文；“—”表示教学示例或主机实现习惯（画面中已注明）。", "",
                  "| 画面说法 | 出处 | 原文要点 / 说明 |", "|---|---|---|"]
        for a, b, c in CHECKS.get(vid, []):
            lines.append(f"| {a} | {b} | {c} |")
        lines += ["", "规范原文的官方下载地址见站点 [规范索引](https://usbtree.gumuhub.com/reference/specs/)。", ""]
        (DST / f"{vid}.md").write_text("\n".join(lines), encoding="utf-8")
        print("wrote", DST / f"{vid}.md")


if __name__ == "__main__":
    main()
